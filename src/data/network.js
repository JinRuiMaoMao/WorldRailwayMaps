/** 兼容旧引用 */
export const CITIES = Object.fromEntries(
  Object.values(PLACES)
    .filter((p) => p.metro)
    .map((p) => [p.id, p])
);

export const EXTRA_NODES = {};

export function resolveNode(id) {
  return PLACES[id] || EXTRA_NODES[id];
}

export function getCorridorPlaces(corridor) {
  return corridor.path.map((id) => resolveNode(id)).filter(Boolean);
}

/** @deprecated use getCorridorPlaces */
export function getCorridorPoints(corridor) {
  return getCorridorPlaces(corridor);
}

export function metroCitiesUpTo(year) {
  return Object.values(CITIES).filter((c) => c.metro && c.metro <= year);
}

