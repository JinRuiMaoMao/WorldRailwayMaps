function extraOpenDate(line) {
  return line.open || '1988-09-18';
}

function extraEdits() {
  try {
    const live = loadEdits();
    if (live?.extraLines && Object.keys(live.extraLines).length) return live;
  } catch {
    /* bundled fallback */
  }
  return DEFAULT_EDITS;
}

function extraLinePath(line, paths) {
  return (paths[line.id]?.length >= 2 && paths[line.id]) || line.path || [];
}

function extraDateMatch(line, since, until) {
  const open = extraOpenDate(line);
  if (until && open > until) return false;
  if (since && open < since) return false;
  return true;
}

function packStationPts(lines, extras, pack) {
  const pts = [];
  for (const l of Object.values(lines)) {
    if (l.pack !== pack) continue;
    for (const s of extras[l.id] || l.stations || []) {
      if (s.lat != null && s.lng != null) pts.push({ lat: s.lat, lng: s.lng });
    }
  }
  return pts;
}

function pathNearPts(path, pts) {
  if (!path?.length || !pts?.length) return Infinity;
  let best = Infinity;
  for (const p of path) {
    const lat = p[0];
    const lng = p[1];
    for (const t of pts) {
      const d = Math.hypot(lat - t.lat, lng - t.lng);
      if (d < best) best = d;
    }
  }
  return best;
}

function lrtIdentity(until) {
  if (until && until >= '2007-12-02') return { line: '轻铁', color: C.lightRailMtr };
  if (until && until >= '1996-01-01') return { line: '九广轻铁', color: C.lightRail };
  return { line: '轻便铁路', color: C.lightRail };
}

/** 轻铁线位以用户 map-edits 为准；之后只补车站坐标，不再代画线段。 */
function extraLrtSegments({ until = '1988-09-18', since, pack, line, color } = {}) {
  const source = extraEdits();
  const lines = source.extraLines || {};
  const extras = source.extraStations || {};
  const paths = source.paths || {};
  const otherPacks = new Set();
  if (pack) {
    for (const l of Object.values(lines)) {
      if (extraDateMatch(l, since, until) && l.pack && l.pack !== pack) otherPacks.add(l.pack);
    }
  }
  const myPts = pack ? packStationPts(lines, extras, pack) : [];
  const otherPts = [...otherPacks].map((p) => packStationPts(lines, extras, p));
  const segs = Object.values(lines)
    .filter((l) => {
      if (!extraDateMatch(l, since, until)) return false;
      if (pack) {
        if (l.pack === pack) return true;
        if (l.pack) return false;
        const path = extraLinePath(l, paths);
        if (path.length < 2) return false;
        const dMine = pathNearPts(path, myPts);
        if (dMine > 0.02) return false;
        return otherPts.every((pts) => pathNearPts(path, pts) + 1e-9 >= dMine);
      }
      return !l.pack;
    })
    .map((l) => {
      const path = extraLinePath(l, paths);
      return {
        id: l.id,
        line: line || lrtIdentity(until).line,
        color: color || l.color || lrtIdentity(until).color,
        stations: (extras[l.id] || []).map((s) => ({ ...s, keepCoords: true })),
        path,
        opacity: 1,
        weight: 6,
      };
    });
  const distToDock = (path) => {
    if (!path?.length) return 99;
    let best = Infinity;
    for (const p of path) {
      const d = Math.hypot(p[0] - LRT_DOCK.lat, p[1] - LRT_DOCK.lng);
      if (d < best) best = d;
    }
    return best;
  };
  return segs.sort((a, b) => {
    const da = distToDock(a.path);
    const db = distToDock(b.path);
    if (Math.abs(da - db) > 0.003) return da - db;
    const la = a.path.length ? Math.max(...a.path.map((p) => p[1])) : 0;
    const lb = b.path.length ? Math.max(...b.path.map((p) => p[1])) : 0;
    return la - lb;
  });
}

/** 播放时再取用户画线，避免 pack 占位空路径把伸展动画吃掉。 */
export function resolveSceneSegments(sc) {
  if (!sc) return [];
  const baked = sc.segments || [];
  if (!sc.extraLrt) return baked;
  const live = extraLrtSegments(sc.extraLrt);
  const core = baked.filter((s) => !String(s.id || '').startsWith('extra-'));
  const seen = new Set(core.map((s) => s.id));
  return [...core, ...live.filter((s) => s.id && !seen.has(s.id))];
}

